# frozen_string_literal: true

module BundleStateCorpus
  # One spec file's expectations, expect/<name>.yml: case id => column =>
  # its cell, or "0.155" / "0.149" => a cell each where the shapes differ.
  # Written from the code with UPDATE_GOLDENS=1, in flow style (one cell a
  # line), with tmp/bundle_states/review.txt beside it (each cell in words);
  # a run that differs writes tmp/bundle_states/<name>.yml.actual.
  class Goldens
    def self.update? = ENV["UPDATE_GOLDENS"] == "1"

    attr_reader :name

    def initialize(name, ids)
      @name = name
      @ids = ids
      @actual = {}
    end

    def path = File.join(FIXTURES, "expect", "#{@name}.yml")
    def actual_path = File.join(TMP, "#{@name}.yml.actual")

    def expected = @expected ||= File.file?(path) ? (YAML.safe_load_file(path) || {}) : {}

    # The case's cells, one per column and shape, folded where the shapes agree.
    # @param cells [Hash{String => Hash{String => Hash}}] column => shape => cell
    def record(id, cells)
      @actual[id] = cells.transform_values { |by_shape| by_shape.values.uniq.size == 1 ? by_shape.values.first : by_shape }
    end

    # Each column and shape whose cell differs from the expectation, in words.
    def mismatches(id)
      want = expected.fetch(id, {})
      got = @actual.fetch(id)
      (want.keys | got.keys).flat_map do |column|
        SHAPES.filter_map do |shape|
          w = shape_cell(want[column], shape)
          g = shape_cell(got[column], shape)
          "#{id} #{column} (#{shape}):\n  expected #{w.inspect}\n  got      #{g.inspect}" unless w == g
        end
      end
    end

    # After the file's examples: the expectations (UPDATE_GOLDENS=1, only from
    # a run of every case) or, on a mismatch, the .actual file to diff.
    def finish
      return if @actual.empty?

      text = render
      if self.class.update?
        missing = @ids - @actual.keys
        raise "#{@name}: not written, #{missing.size} cases didn't run (#{missing.first(3).join(", ")}…)" unless missing.empty?

        File.write(path, text)
        write_review
      elsif @actual.any? { |id, _| mismatches(id).any? }
        # The cases this run skipped (rspec -e) keep their expected cells, so the diff shows only what changed.
        FileUtils.mkdir_p(TMP)
        File.write(actual_path, render(expected.slice(*@ids).merge(@actual)))
      end
    end

    def hint
      "#{path.delete_prefix("#{Dir.pwd}/")} differs: diff #{path.delete_prefix("#{Dir.pwd}/")} " \
        "#{actual_path.delete_prefix("#{Dir.pwd}/")}. A refactor stops here; only a commit the plan names as a cell " \
        "change regenerates (UPDATE_GOLDENS=1), and its changed cells are reviewed (docs/testing.md)"
    end

    private

    def shape_cell(cell, shape) = cell.is_a?(Hash) && cell.key?(shape) ? cell[shape] : cell

    def ordered(cells = @actual) = @ids.select { |id| cells.key?(id) }.to_h { |id| [id, cells[id]] }

    def render(cells = @actual)
      lines = ["# Generated by spec/samagotchi/memory_bundle/file_state_corpus/#{@name}_spec.rb (UPDATE_GOLDENS=1).",
               "# Don't edit: a regenerated cell is reviewed (docs/testing.md, the bundle-state corpus)."]
      ordered(cells).each do |id, columns|
        lines << "#{id}:"
        columns.each do |column, cell|
          if cell.key?(SHAPES.first)
            lines << "  #{column}:"
            cell.each { |shape, value| lines << "    #{shape.to_json}: #{flow(value)}" }
          else
            lines << "  #{column}: #{flow(cell)}"
          end
        end
      end
      text = "#{lines.join("\n")}\n"
      raise "#{@name}: the YAML doesn't read back as written" unless YAML.safe_load(text) == ordered(cells)

      text
    end

    def flow(cell) = "{#{cell.map { |k, v| "#{k}: #{scalar(v)}" }.join(", ")}}"

    PLAIN = /\A[A-Za-z][A-Za-z0-9_ .()-]*\z/
    RESERVED = /\A(?:true|false|null|yes|no|on|off|y|n|~)\z/i

    def scalar(value)
      case value
      when Array then "[#{value.map { |v| scalar(v) }.join(", ")}]"
      when String then value.match?(PLAIN) && !value.match?(RESERVED) && !value.end_with?(" ") ? value : value.to_json
      else value.to_json
      end
    end

    # Each cell in words, by column, for the one-time read of a regenerated file.
    def write_review
      FileUtils.mkdir_p(TMP)
      columns = ordered.values.flat_map(&:keys).uniq
      lines = columns.flat_map do |column|
        ["== #{column}"] + ordered.flat_map do |id, cells|
          cell = cells.fetch(column)
          (cell.key?(SHAPES.first) ? cell : { "both" => cell }).map do |shape, value|
            "#{id} [#{shape}]: #{value.map { |k, v| "#{k} #{v.inspect}" }.join("; ")}"
          end
        end
      end
      File.write(File.join(TMP, "review.#{@name}.txt"), "#{lines.join("\n")}\n")
    end
  end
end
